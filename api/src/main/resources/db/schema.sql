-- Parámetros generales del cuestionario (una sola fila)
CREATE TABLE IF NOT EXISTS configuracion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instrucciones VARCHAR(2000) NOT NULL,
    tiempo_maximo_minutos INT NOT NULL,
    tiempo_maximo_activo_horas INT NOT NULL,
    cantidad_maxima_accesos INT NOT NULL,
    cantidad_preguntas_por_bloque INT NOT NULL
);

-- Bloques (pasos del wizard) en que se divide un cuestionario
CREATE TABLE IF NOT EXISTS bloque_cuestionario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuestionario_id BIGINT NOT NULL,
    numero INT NOT NULL,
    completado BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_bloque_cuestionario FOREIGN KEY (cuestionario_id) REFERENCES cuestionario (id),
    CONSTRAINT uk_bloque_cuestionario_numero UNIQUE (cuestionario_id, numero)
);

-- Preguntas elegidas al azar para el cuestionario, ubicadas en un bloque
CREATE TABLE IF NOT EXISTS pregunta_asignada (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bloque_id BIGINT NOT NULL,
    pregunta_id BIGINT NOT NULL,
    nro_orden INT NOT NULL,
    CONSTRAINT fk_pregunta_asignada_bloque FOREIGN KEY (bloque_id) REFERENCES bloque_cuestionario (id),
    CONSTRAINT fk_pregunta_asignada_pregunta FOREIGN KEY (pregunta_id) REFERENCES pregunta (id)
);

CREATE TABLE IF NOT EXISTS respuesta_cuestionario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuestionario_id BIGINT NOT NULL,
    pregunta_id BIGINT NOT NULL,
    opcion_respuesta_id BIGINT NOT NULL,
    CONSTRAINT fk_respuesta_cuestionario FOREIGN KEY (cuestionario_id) REFERENCES cuestionario (id) ON DELETE CASCADE,
    CONSTRAINT fk_respuesta_pregunta FOREIGN KEY (pregunta_id) REFERENCES pregunta (id),
    CONSTRAINT fk_respuesta_opcion FOREIGN KEY (opcion_respuesta_id) REFERENCES pregunta_opcion_respuesta (id),
    CONSTRAINT uk_respuesta_cuestionario_pregunta UNIQUE (cuestionario_id, pregunta_id)
);

CREATE TABLE IF NOT EXISTS resultado_competencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuestionario_id BIGINT NOT NULL,
    competencia_id BIGINT NOT NULL,
    puntaje DOUBLE PRECISION NOT NULL,
    CONSTRAINT fk_resultado_cuestionario FOREIGN KEY (cuestionario_id) REFERENCES cuestionario (id) ON DELETE CASCADE,
    CONSTRAINT fk_resultado_competencia FOREIGN KEY (competencia_id) REFERENCES competencia (id),
    CONSTRAINT uk_resultado_cuestionario_competencia UNIQUE (cuestionario_id, competencia_id),
    CONSTRAINT ck_resultado_puntaje CHECK (puntaje >= 0 AND puntaje <= 10)
);

-- Opción elegida por el candidato para una pregunta asignada
CREATE TABLE IF NOT EXISTS respuesta_candidato (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pregunta_asignada_id BIGINT NOT NULL UNIQUE,
    opcion_id BIGINT NOT NULL,
    fecha_respuesta TIMESTAMP NOT NULL,
    CONSTRAINT fk_respuesta_pregunta_asignada FOREIGN KEY (pregunta_asignada_id) REFERENCES pregunta_asignada (id),
    CONSTRAINT fk_respuesta_opcion FOREIGN KEY (opcion_id) REFERENCES pregunta_opcion_respuesta (id)
);

-- Resultado del cuestionario completo
CREATE TABLE IF NOT EXISTS resultado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuestionario_id BIGINT NOT NULL UNIQUE,
    puntaje_obtenido DOUBLE PRECISION NOT NULL,
    fecha_calculo TIMESTAMP NOT NULL,
    CONSTRAINT fk_resultado_cuestionario FOREIGN KEY (cuestionario_id) REFERENCES cuestionario (id)
);

-- Puntaje por competencia, comparable con la ponderación requerida por el puesto
CREATE TABLE IF NOT EXISTS resultado_competencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resultado_id BIGINT NOT NULL,
    caracteristica_puesto_id BIGINT NOT NULL,
    total_competencia DOUBLE PRECISION NOT NULL,
    CONSTRAINT fk_res_competencia_resultado FOREIGN KEY (resultado_id) REFERENCES resultado (id),
    CONSTRAINT fk_res_competencia_caracteristica FOREIGN KEY (caracteristica_puesto_id) REFERENCES caracteristica_puesto (id)
);

-- Puntaje por factor evaluado
CREATE TABLE IF NOT EXISTS resultado_factor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resultado_competencia_id BIGINT NOT NULL,
    factor_id BIGINT NOT NULL,
    total_factor DOUBLE PRECISION NOT NULL,
    CONSTRAINT fk_res_factor_competencia FOREIGN KEY (resultado_competencia_id) REFERENCES resultado_competencia (id),
    CONSTRAINT fk_res_factor_factor FOREIGN KEY (factor_id) REFERENCES factor (id)
);
