-- Esquema de base de datos (H2 en modo PostgreSQL)

CREATE TABLE IF NOT EXISTS competencia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(20) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(500) NOT NULL,
    tipo VARCHAR(50),
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    usuario_eliminacion BIGINT
);

CREATE TABLE IF NOT EXISTS factor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    nro_orden INT NOT NULL,
    competencia_id BIGINT NOT NULL,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    usuario_eliminacion BIGINT,
    CONSTRAINT uk_factor_codigo UNIQUE (codigo),
    CONSTRAINT uk_factor_nombre UNIQUE (nombre),
    CONSTRAINT uk_factor_competencia_orden UNIQUE (competencia_id, nro_orden),
    CONSTRAINT fk_factor_competencia FOREIGN KEY (competencia_id) REFERENCES competencia (id)
);

CREATE TABLE IF NOT EXISTS puesto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL UNIQUE,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(500) NOT NULL,
    empresa VARCHAR(100) NOT NULL,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    usuario_eliminacion BIGINT
);

CREATE TABLE IF NOT EXISTS caracteristica_puesto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    puesto_id BIGINT NOT NULL,
    competencia_id BIGINT NOT NULL,
    ponderacion_requerida DOUBLE PRECISION NOT NULL,
    CONSTRAINT fk_caracteristica_puesto FOREIGN KEY (puesto_id) REFERENCES puesto (id) ON DELETE CASCADE,
    CONSTRAINT fk_caracteristica_competencia FOREIGN KEY (competencia_id) REFERENCES competencia (id),
    CONSTRAINT uk_puesto_competencia UNIQUE (puesto_id, competencia_id)
);

CREATE TABLE IF NOT EXISTS pregunta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    enunciado VARCHAR(1000) NOT NULL,
    descripcion VARCHAR(500),
    factor_id BIGINT NOT NULL,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    usuario_eliminacion BIGINT,
    CONSTRAINT fk_pregunta_factor FOREIGN KEY (factor_id) REFERENCES factor (id)
);

CREATE TABLE IF NOT EXISTS pregunta_opcion_respuesta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pregunta_id BIGINT NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(500),
    nro_orden INT NOT NULL,
    ponderacion DOUBLE PRECISION NOT NULL,
    CONSTRAINT fk_opcion_pregunta FOREIGN KEY (pregunta_id) REFERENCES pregunta (id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS opcion_respuesta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    descripcion VARCHAR(500) NOT NULL
);

CREATE TABLE IF NOT EXISTS item_opcion_respuesta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    opcion_respuesta_id BIGINT NOT NULL,
    orden INT NOT NULL,
    descripcion VARCHAR(500) NOT NULL,
    CONSTRAINT fk_item_opcion_respuesta FOREIGN KEY (opcion_respuesta_id) REFERENCES opcion_respuesta (id) ON DELETE CASCADE,
    CONSTRAINT uk_item_opcion_orden UNIQUE (opcion_respuesta_id, orden),
    CONSTRAINT uk_item_opcion_descripcion UNIQUE (opcion_respuesta_id, descripcion)
);

CREATE TABLE IF NOT EXISTS candidato (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nro_candidato BIGINT UNIQUE,
    tipo_documento VARCHAR(10) NOT NULL,
    nro_documento VARCHAR(20) NOT NULL,
    apellido VARCHAR(100) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    fecha_nacimiento DATE,
    genero VARCHAR(10),
    nacionalidad VARCHAR(50),
    email VARCHAR(100),
    escolaridad VARCHAR(100),
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    usuario_eliminacion BIGINT,
    CONSTRAINT uk_candidato_documento UNIQUE (tipo_documento, nro_documento)
);

-- CU 025: una Evaluacion agrupa los cuestionarios generados para un puesto en una misma operación
CREATE TABLE IF NOT EXISTS evaluacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    puesto_id BIGINT NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL,
    usuario_creacion BIGINT,
    CONSTRAINT fk_evaluacion_puesto FOREIGN KEY (puesto_id) REFERENCES puesto (id)
);

CREATE TABLE IF NOT EXISTS cuestionario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidato_id BIGINT NOT NULL,
    evaluacion_id BIGINT,
    puesto_id BIGINT,
    estado VARCHAR(20) NOT NULL,
    clave_acceso VARCHAR(8) NOT NULL,
    fecha_creacion TIMESTAMP,
    fecha_inicio TIMESTAMP,
    fecha_finalizacion TIMESTAMP,
    -- CU 026: control de accesos y tiempos (los parámetros se copian de la configuración al crearlo)
    fecha_ultimo_ingreso TIMESTAMP,
    fecha_cambio_estado TIMESTAMP,
    cantidad_accesos INT NOT NULL DEFAULT 0,
    tiempo_maximo_minutos INT,
    tiempo_maximo_activo_horas INT,
    cantidad_maxima_accesos INT,
    cantidad_preguntas_por_bloque INT,
    eliminado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_eliminacion TIMESTAMP,
    usuario_eliminacion BIGINT,
    CONSTRAINT fk_cuestionario_candidato FOREIGN KEY (candidato_id) REFERENCES candidato (id),
    CONSTRAINT fk_cuestionario_evaluacion FOREIGN KEY (evaluacion_id) REFERENCES evaluacion (id)
);


